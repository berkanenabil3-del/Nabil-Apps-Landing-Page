const contactNumber = "213661106568";
const savedLang = localStorage.getItem("nabilapps-language") || "fr";
const savedTheme = localStorage.getItem("nabilapps-theme") || "light";

function applyLanguage(lang){
  const dict = translations[lang] || translations.fr;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.getElementById("currentLanguage").textContent = lang.toUpperCase();
  localStorage.setItem("nabilapps-language", lang);
  document.getElementById("languageMenu").classList.remove("open");
  document.getElementById("languageBtn").setAttribute("aria-expanded","false");
}

function applyTheme(theme){
  document.body.classList.toggle("dark", theme === "dark");
  const icon = document.querySelector("#theme-toggle i");
  icon.className = theme === "dark" ? "fas fa-sun" : "fas fa-moon";
  localStorage.setItem("nabilapps-theme", theme);
}

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(savedLang);
  applyTheme(savedTheme);

  const menuToggle = document.getElementById("mobileMenuToggle");
  const nav = document.getElementById("mainNav");

  menuToggle.addEventListener("click", () => {
    nav.classList.toggle("open");
    const opened = nav.classList.contains("open");
    menuToggle.setAttribute("aria-expanded", opened);
    menuToggle.querySelector("i").className = opened ? "fas fa-xmark" : "fas fa-bars";
  });

  document.querySelectorAll("#mainNav a").forEach(link => {
    link.addEventListener("click", () => {
      nav.classList.remove("open");
      menuToggle.setAttribute("aria-expanded", "false");
      menuToggle.querySelector("i").className = "fas fa-bars";
    });
  });

  document.getElementById("theme-toggle").addEventListener("click", () => {
    applyTheme(document.body.classList.contains("dark") ? "light" : "dark");
  });

  const languageBtn = document.getElementById("languageBtn");
  const languageMenu = document.getElementById("languageMenu");
  languageBtn.addEventListener("click", e => {
    e.stopPropagation();
    languageMenu.classList.toggle("open");
    languageBtn.setAttribute("aria-expanded", languageMenu.classList.contains("open"));
  });

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });

  document.addEventListener("click", e => {
    if (!e.target.closest(".language-dropdown")) {
      languageMenu.classList.remove("open");
      languageBtn.setAttribute("aria-expanded","false");
    }
  });

  const form = document.getElementById("contactForm");
  form.addEventListener("submit", e => {
    e.preventDefault();
    const name = document.getElementById("contactName").value.trim();
    const email = document.getElementById("contactEmail").value.trim();
    const phone = document.getElementById("contactPhone").value.trim();
    const project = document.getElementById("contactProject").value.trim();

    if (!name || !email) return;

    const lang = localStorage.getItem("nabilapps-language") || "fr";
    let title = "Bonjour Nabil Apps";
    if(lang === "en") title = "Hello Nabil Apps";
    if(lang === "ar") title = "السلام عليكم Nabil Apps";

    const message =
      `${title}%0A%0A` +
      `Nom / Name: ${encodeURIComponent(name)}%0A` +
      `Email: ${encodeURIComponent(email)}%0A` +
      `Téléphone: ${encodeURIComponent(phone || "-")}%0A` +
      `Projet: ${encodeURIComponent(project || "-")}`;

    window.open(`https://wa.me/${contactNumber}?text=${message}`, "_blank");
  });

  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if(entry.isIntersecting) entry.target.classList.add("visible");
    });
  }, {threshold:.12});

  document.querySelectorAll(".reveal").forEach(el => observer.observe(el));

  const top = document.getElementById("backToTop");
  window.addEventListener("scroll", () => {
    top.classList.toggle("show", window.scrollY > 500);
  });
  top.addEventListener("click", () => window.scrollTo({top:0, behavior:"smooth"}));
});
